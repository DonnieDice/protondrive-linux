#!/usr/bin/env bash
# Provision build dependencies on persistent VM test hosts.
# Runs on the GitLab runner which has SSH access to the VM subnet.
# Targets: debian13 (192.168.1.120, issue #14 / parent #3) and
# debian12 (192.168.1.162, issue #26 / parent #2). Each issue's CI run
# provisions the target it owns and reports evidence for it; see
# PD_TARGETS below. Transport: VM_SSH_KEY CI variable when set, else the
# runner-mounted /root/.ssh config (see scripts/ci/lib/_vm_common.sh).

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/../lib/_vm_common.sh"

# Provisioning targets, comma-separated labels. Default: both Debian hosts
# (the runner is shared infrastructure; both issues #14 and #26 run this job).
# A CI run for one issue can scope its own evidence with PD_TARGETS:
#   PD_TARGETS=debian13  (issue #14)   PD_TARGETS=debian12  (issue #26)
# Scoping only selects which host(s) this run provisions and verifies; it
# never provisions anything outside the list.
PD_TARGETS="${PD_TARGETS:-debian12,debian13}"

DEBIAN13_IP="192.168.1.120"
DEBIAN12_IP="192.168.1.162"

_pd_ip_for() {
  case "$1" in
    debian13) echo "$DEBIAN13_IP" ;;
    debian12) echo "$DEBIAN12_IP" ;;
    *) echo "" ;;
  esac
}

_pd_has_target() {
  local t
  for t in ${PD_TARGETS//,/ }; do
    [ "$t" = "$1" ] && return 0
  done
  return 1
}

# Bounded, non-destructive disk reclaim. Per operator safety review
# (note 41385 on MR !12): no removal of /usr/share/{doc,man,locale,info,
# zoneinfo,terminfo}, no package purges, no rustup component removal —
# those deletions are not needed now that debian13's root disk is 100 GiB
# (68G free, operator resize 2026-10-15) and they would damage the shared
# hosts. Only cache/data locations that are regenerated by the tools that
# own them are cleaned, and every path is scoped to this provision run.
_pd_bounded_cleanup() {
  local ip="$1" label="$2"
  echo "--- bounded disk reclaim on $label (caches only, no system deletions) ---"
  run_on_vm "$ip" '
    set -euo pipefail
    echo "before:"; df -h /
    apt-get clean 2>/dev/null || true
    rm -rf /var/lib/apt/lists/partial/* /var/cache/apt/archives/partial/* 2>/dev/null || true
    journalctl --vacuum-size=200M 2>/dev/null || true
    # /var/tmp is the on-disk build root; /tmp/pd-deploy is the pre-2026-10
    # location that landed on the 735M tmpfs and caused ENOSPC (os error 28)
    # during cargo release builds — purge it so the tmpfs stays clean.
    rm -rf /var/tmp/pd-deploy 2>/dev/null || true
    rm -rf /tmp/pd-deploy 2>/dev/null || true
    echo "after:"; df -h /
  ' || echo "WARN: bounded cleanup reported errors on $label (continuing)"
}

provision_build_deps() {
  local ip="$1" label="$2"
  echo "=== Provisioning build dependencies on $label ($ip) ==="

  _pd_bounded_cleanup "$ip" "$label"

  # The libjavascriptcoregtk dev package name differs between Debian 12
  # (bookworm: libjavascriptcoregtk-4.1-0-dev) and Debian 13 (trixie:
  # libjavascriptcoregtk-4.1-dev). Try both lists; the one containing a
  # package that exists on this distro will succeed.
  run_on_vm "$ip" "
    DEBIAN_FRONTEND=noninteractive apt-get update -qq &&
    DEBIAN_FRONTEND=noninteractive apt-get install -y -q \
      cmake libssl-dev pkg-config build-essential \
      git curl wget file patchelf python3 ca-certificates \
      libgtk-3-dev libwebkit2gtk-4.1-dev libayatana-appindicator3-dev \
      librsvg2-dev libsoup-3.0-dev libjavascriptcoregtk-4.1-0 \
      libwebkit2gtk-4.1-0 libgtk-3-0 libsoup-3.0-0 libayatana-appindicator3-1 \
      libjavascriptcoregtk-4.1-0 libjavascriptcoregtk-4.1-0-dev || \
    DEBIAN_FRONTEND=noninteractive apt-get install -y -q \
      cmake libssl-dev pkg-config build-essential \
      git curl wget file patchelf python3 ca-certificates \
      libgtk-3-dev libwebkit2gtk-4.1-dev libayatana-appindicator3-dev \
      librsvg2-dev libsoup-3.0-dev libjavascriptcoregtk-4.1-dev \
      libwebkit2gtk-4.1-0 libgtk-3-0 libsoup-3.0-0 libayatana-appindicator3-1
  " || {
    echo "FAIL: apt install failed on $label"
    return 1
  }

  # Verify installed tools
  run_on_vm "$ip" "cmake --version" || {
    echo "FAIL: cmake not working on $label"
    return 1
  }
  run_on_vm "$ip" "pkg-config --version" || {
    echo "FAIL: pkg-config not working on $label"
    return 1
  }
  run_on_vm "$ip" "gcc --version | head -1" || {
    echo "FAIL: gcc not working on $label"
    return 1
  }

  # Install rustup if not present; default toolchain stable.
  # Deploy a script to the VM instead of embedding multi-line shell in a
  # double-quoted run_on_vm argument: the runner-side expansion of
  # $HOME/$PATH inside the escaped inline form corrupted the remote PATH
  # ("curl: sh: rustup: command not found", pipeline 3858 job 37378) even
  # though apt had just installed curl. The heredoc below is transmitted
  # verbatim (single-quoted delimiter) so every expansion happens on the
  # VM with the VM's own environment — the same pattern that already works
  # for the build script in verify_protondrive_build.
  local rust_script='
    set -euo pipefail
    export PATH="$HOME/.cargo/bin:$PATH"
    if ! command -v rustup >/dev/null 2>&1; then
      curl --proto =https --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --default-toolchain stable --no-modify-path
    else
      rustup default stable 2>/dev/null || rustup default stable
    fi
    export PATH="$HOME/.cargo/bin:$PATH"
    rustup show
    rustc --version
    cargo --version
  '
  run_on_vm "$ip" "mkdir -p /var/tmp/pd-deploy && cat > /var/tmp/pd-deploy/rust-install.sh <<'RUST_SCRIPT_EOF'
$rust_script
RUST_SCRIPT_EOF
chmod +x /var/tmp/pd-deploy/rust-install.sh && /var/tmp/pd-deploy/rust-install.sh" || {
    echo "FAIL: rustup install failed on $label"
    return 1
  }

  echo "=== Build dependencies provisioned on $label ==="
  return 0
}

verify_protondrive_build() {
  local ip="$1" label="$2"
  echo "=== Verifying protondrive-linux build on $label ($ip) ==="

  _pd_bounded_cleanup "$ip" "$label"

  # Transfer the runner's own checkout (excluding WebClients and .git) instead
  # of cloning from GitLab: the project is private (anonymous clone fails) and
  # VM-side DNS has been unreliable (pipeline 1916/2099-era outages).
  local workdir=/var/tmp/pd-deploy/protondrive-linux
  local srcdir="${CI_PROJECT_DIR:-$(pwd)}"
  tar -C "$srcdir" --exclude='./.git' --exclude='./WebClients' -cf - . |
    run_on_vm "$ip" "rm -rf '$workdir' && mkdir -p '$workdir' && tar -C '$workdir' -xf -"

  # Write a build script to the VM rather than embedding complex shell quoting
  # in run_on_vm. The build script runs a cargo release build in src-tauri/.
  # generate_context!() in src/main.rs loads tauri.conf.json (which declares
  # frontendDist) at compile time, so cargo build FAILS when the dist directory
  # is absent — the repo's own test:rust job stubs it identically
  # (.gitlab/workflows/tests.yml). The transfer step excludes WebClients
  # (the full web bundle build is out of scope for issues #14/#26), so
  # build.sh creates a placeholder dist here: enough to satisfy the tauri
  # build, exactly like the repo's own test:rust job does.
  local build_script='
    set -euo pipefail
    export PATH="$HOME/.cargo/bin:$PATH"
    cd "$1/src-tauri"
    mkdir -p ../WebClients/applications/drive/dist
    echo "<!doctype html><html><body>dist placeholder for release build</body></html>" \
      > ../WebClients/applications/drive/dist/index.html
    cargo build --release
    echo "Post-build disk:"
    df -h /
    # Cargo run from src-tauri/ puts the binary in target/release/
    BINARY=target/release/proton-drive
    [ -f "$BINARY" ] && echo "BUILD SUCCESS: $BINARY" || {
        echo "BUILD FAILED: binary not found at $BINARY"; exit 1;
    }
    sha256sum "$BINARY"
    "$BINARY" --version 2>/dev/null || echo "binary present; no --version flag"
  '

  run_on_vm "$ip" "cat > /var/tmp/pd-deploy/build.sh <<'BUILD_SCRIPT_EOF'
$build_script
BUILD_SCRIPT_EOF
chmod +x /var/tmp/pd-deploy/build.sh && /var/tmp/pd-deploy/build.sh /var/tmp/pd-deploy/protondrive-linux" || {
    echo "FAIL: protondrive-linux build failed on $label"
    return 1
  }

  echo "=== protondrive-linux builds successfully on $label ==="
  return 0
}

# Main execution
_pd_ssh_init

echo "Starting VM build dependency provisioning (targets: $PD_TARGETS)..."

OVERALL_RC=0

# Issue #14 scope: debian13 (parent #3). The debian13 steps are fatal for
# this script when debian13 is in PD_TARGETS: issue #14's acceptance
# criteria are exactly this provision + release-build evidence.
if _pd_has_target debian13; then
  provision_build_deps "$DEBIAN13_IP" "debian13" || exit 1
  verify_protondrive_build "$DEBIAN13_IP" "debian13" || exit 1
  echo "=== debian13 BUILD DEPENDENCIES PROVISIONED AND VERIFIED ==="
fi

# Issue #26 scope: debian12 (parent #2). Provision + verify as the routed
# execution dependency for parent issue #2's acceptance criteria. When the
# job is scoped to one issue (PD_TARGETS), the other host's step is
# skipped entirely, so one issue's evidence is never masked by the
# other host's state (the pipeline-4903 debian12 outage made job 60099
# exit 1 after debian13 had already succeeded).
if _pd_has_target debian12; then
  provision_build_deps "$DEBIAN12_IP" "debian12" || exit 1
  verify_protondrive_build "$DEBIAN12_IP" "debian12" || exit 1
  echo "=== debian12 BUILD DEPENDENCIES PROVISIONED AND VERIFIED ==="
fi

echo "=== VM BUILD DEPENDENCY PROVISIONING DONE (targets: $PD_TARGETS, rc=$OVERALL_RC) ==="
exit "$OVERALL_RC"
